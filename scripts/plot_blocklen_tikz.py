# plot_blocklen_png keeps matplotlib inside the figure functions, so importing it
# here stays stdlib-only and the two emitters cannot drift apart on the data.
from plot_blocklen_png import (  # noqa: E402
    DEFAULT_RUNS, PRETTY, collect, structure_arms,
)

REPO_ROOT = _SCRIPTS_DIR.parent
DEFAULT_OUT = REPO_ROOT / "docs" / "figures" / "blocklen-tikz"
DEFAULT_ARMS = ["cat1_baseline", "cat5_regularizer"]
#: Overridden per invocation with --color; these are the paper's two hues.
DEFAULT_COLORS = {
    "cat1_baseline": "008300",
    # A two-hex value draws the line in the first tone with the second dashed
    # over it, so the colours alternate along it.
    "cat5_regularizer": ("EB6834", "EDA100"),
}
#: Shape as well as colour, so the series survive greyscale printing.
MARKS = ["*", "square*", "triangle*", "diamond*"]
GREY = "8A8985"

BODY_NOTE = r"""% Generated by scripts/plot_blocklen_tikz.py -- regenerating overwrites this file.
% Figure body only (no \documentclass). Two ways to use it:
%   1. compile the sibling standalone wrapper, or
%   2. \input{} this file inside a figure environment in the paper -- the paper
%      preamble then needs: \usepackage{pgfplots} \pgfplotsset{compat=1.18}
%      and, if the .dat files are not beside the main .tex,
%      \pgfplotsset{table/search path={<dir holding the .dat files>}}
"""

WRAPPER = r"""% Generated by scripts/plot_blocklen_tikz.py -- regenerating overwrites this file.
% Standalone wrapper; all the figure content lives in the _body.tex it inputs.
\documentclass[tikz, border=2pt]{standalone}
\usepackage{pgfplots}
\pgfplotsset{compat=1.18}
\begin{document}
\input{@@BODY@@}
\end{document}
"""


def color_macro(cat: str) -> str:
    """``cat5_regularizer`` -> ``ndCat5`` -- the repo's existing macro spelling."""
    m = re.match(r"(cat\d+)", cat)
    stem = m.group(1) if m else re.sub(r"[^A-Za-z0-9]+", "", cat)
    return "nd" + stem[:1].upper() + stem[1:]


def tex_escape(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("_", r"\_")
             .replace("&", r"\&").replace("%", r"\%").replace("#", r"\#"))


def hexes(colors, cat) -> list[str]:
    """One hex, or two for a series drawn as an alternating two-tone line."""
    v = colors[cat]
    return list(v) if isinstance(v, (list, tuple)) else [v]


def two_tone(colors, cat) -> bool:
    return len(hexes(colors, cat)) > 1


def dash_defs(arms, colors, on="3.6pt", off="3.6pt") -> str:
    """The dash knobs, or nothing when no series needs them."""
    if not any(two_tone(colors, c) for c in arms):
        return ""
    return DASH_DEFS.replace("@@ON@@", on).replace("@@OFF@@", off)


def color_defs(arms, colors) -> str:
    names = []
    for c in arms:
        names.append((color_macro(c), hexes(colors, c)[0], PRETTY.get(c, c)))
        if two_tone(colors, c):
            names.append((color_macro(c) + "Alt", hexes(colors, c)[1],
                          f"{PRETTY.get(c, c)}, alternating tone"))
    names.append(("ndRef", GREY, "fair-coin / identity reference"))
    width = max(len(n) for n, _, _ in names)
    return "\n".join(f"\\definecolor{{{n}}}{{HTML}}{{{h.upper()}}}"
                     f"{' ' * (width - len(n))}  % {note}" for n, h, note in names)


#: Dash rhythm of a two-tone line, as knobs so it can be retuned without a
#: regeneration. The solid tone shows through the gaps of the dashed one.
DASH_DEFS = r"""
%% Dash rhythm of the two-tone series: the second colour is dashed ON TOP of
%% the first, so these two lengths set how the colours alternate.
\def\DashOn{@@ON@@}
\def\DashOff{@@OFF@@}
"""


def line_series(cat, i, colors, xcol, ycol, dat, indent="    ") -> list[str]:
    """``\\addplot`` lines plus an explicit legend key for one line series.

    A two-tone series is one line drawn twice -- solid in the first colour, then
    dashed in the second on top -- so the colours alternate along it. Both are
    ``forget plot`` and the key is built by hand, because pgfplots would
    otherwise put two entries in the legend for what is one series.
    """
    cm, mk = color_macro(cat), MARKS[i % len(MARKS)]
    mark_opts = (f"mark={mk}, mark size=1.3pt,"
                 f" mark options={{solid, fill={cm}, draw={cm}}}")
    out = []
    if two_tone(colors, cat):
        cm2 = cm + "Alt"
        out.append(f"{indent}%% two-tone: solid {cm} with {cm2} dashed over it")
        out.append(f"{indent}\\addplot[{cm}, line width=1.1pt, {mark_opts}, forget plot]"
                   f" table[x={xcol}, y={ycol}] {{{dat}}};")
        out.append(f"{indent}\\addplot[{cm2}, line width=1.1pt, mark=none,"
                   f" dash pattern=on \\DashOn off \\DashOff, forget plot]"
                   f" table[x={xcol}, y={ycol}] {{{dat}}};")
        out.append(f"{indent}\\addlegendimage{{legend image code/.code={{%")
        out.append(f"{indent}  \\draw[{cm}, line width=1.1pt] (0cm,0cm) -- (0.6cm,0cm);")
        out.append(f"{indent}  \\draw[{cm2}, line width=1.1pt,"
                   f" dash pattern=on \\DashOn off \\DashOff] (0cm,0cm) -- (0.6cm,0cm);")
        out.append(f"{indent}  \\draw[{cm}, {mark_opts}] plot coordinates {{(0.3cm,0cm)}};")
        out.append(f"{indent}}}}}")
    else:
        out.append(f"{indent}\\addplot[{cm}, line width=1.1pt, {mark_opts}, forget plot]"
                   f" table[x={xcol}, y={ycol}] {{{dat}}};")
        out.append(f"{indent}\\addlegendimage{{{cm}, line width=1.1pt, {mark_opts}}}")
    out.append(f"{indent}\\addlegendentry{{{tex_escape(PRETTY.get(cat, cat))}}}")
    return out


def ref_series(dat, xcol, ycol, label="random signs", indent="    ") -> list[str]:
    """The dashed grey reference, with a key built the same explicit way."""
    return [
        f"{indent}\\addplot[ndRef, line width=0.9pt, dashed, forget plot]"
        f" table[x={xcol}, y={ycol}] {{{dat}}};",
        f"{indent}\\addlegendimage{{ndRef, line width=0.9pt, dashed}}",
        f"{indent}\\addlegendentry{{{label}}}",
    ]


def fmt(v) -> str:
    """``nan`` for a missing point -- pgfplots skips it under unbounded coords=jump."""
    if v is None:
        return "nan"
    return f"{v:.6g}" if isinstance(v, float) else str(v)


def write_dat(path: Path, header: list[str], rows: list[list]) -> None:
    lines = [" ".join(header)]
    lines += [" ".join(fmt(v) for v in row) for row in rows]
    path.write_text("\n".join(lines) + "\n")


def write_figure(out: Path, name: str, body: str, libs: str = "") -> list[Path]:
    body_path = out / f"{name}_body.tex"
    note = BODY_NOTE
    if libs:
        note += f"%      \\usepgfplotslibrary{{{libs}}}\n"
    body_path.write_text(note + body)
    wrapper = out / f"{name}.tex"
    text = WRAPPER.replace("@@BODY@@", body_path.name)
    if libs:
        text = text.replace("\\pgfplotsset{compat=1.18}",
                            f"\\pgfplotsset{{compat=1.18}}\n\\usepgfplotslibrary{{{libs}}}")
    wrapper.write_text(text)
    return [body_path, wrapper]


