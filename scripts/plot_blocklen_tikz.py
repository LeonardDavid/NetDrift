def _packing_table(arms, packing) -> str:
    rows = ["| category | cells | blocks | mean block length |",
            "|---|---|---|---|"]
    for c in arms:
        cells, blocks = packing["cells"][c], packing["totals"][c]
        rows.append(f"| {PRETTY.get(c, c)} | {cells:,} | {blocks:,} |"
                    f" {cells / blocks:.3f} |")
    return "\n".join(rows)


def _wrap_layers(names: list[str], per_line: int = 3) -> str:
    rows = [names[i:i + per_line] for i in range(0, len(names), per_line)]
    return "\n".join("  ".join(f"{n:<22s}" for n in r).rstrip() for r in rows)


