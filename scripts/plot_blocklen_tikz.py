def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", type=Path, default=DEFAULT_RUNS)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--rt-error", default="1e-05")
    ap.add_argument("--only", nargs="+", metavar="CATEGORY", default=DEFAULT_ARMS,
                    help="categories to plot (default: %(default)s)")
    ap.add_argument("--color", action="append", default=[], metavar="CAT=HEX",
                    help="override a series colour: HEX, or HEX/HEX for a line "
                         "that alternates between two tones, e.g. "
                         "cat5_regularizer=EB6834/EDA100")
    ap.add_argument("--pair-y", choices=["share", "count"], default="count",
                    help="which fig1a y-axis the side-by-side figure uses. "
                         "Default `count`: both arms store the same number of "
                         "cells, so counts share a denominator and the panel "
                         "conserves mass. (default: %(default)s)")
    ap.add_argument("--fig1a-y", nargs="+", choices=["share", "count"],
                    default=["share", "count"], metavar="VIEW",
                    help="y-axis for fig1a: share of all blocks, number of blocks, "
                         "or both (default). Both read the same .dat.")
    args = ap.parse_args()

    colors = dict(DEFAULT_COLORS)
    for spec in args.color:
        cat, _, hexval = spec.partition("=")
        parts = hexval.split("/")
        if not (1 <= len(parts) <= 2
                and all(re.fullmatch(r"[0-9A-Fa-f]{6}", h) for h in parts)):
            raise SystemExit(f"--color {spec}: need HEX or HEX/HEX (6-digit), "
                             f"got {hexval!r}")
        colors[cat] = parts[0] if len(parts) == 1 else tuple(parts)

    bundle = collect(args.runs, args.rt_error, only=args.only)
    arms = structure_arms(bundle)
    dropped = [c for c in bundle["categories"] if c not in arms]
    missing = [c for c in arms if c not in colors]
    if missing:
        raise SystemExit("no colour for " + ", ".join(missing) + " -- pass --color")

    args.out.mkdir(parents=True, exist_ok=True)
    written = []
    f1, lmax, packing = build_fig1a(args.out, bundle, arms, colors, args.fig1a_y)
    f2, kmax = build_fig2a(args.out, bundle, arms, colors)
    f4, stats = build_fig4a(args.out, bundle, arms, colors)
    fp, pair_name = build_pair(args.out, bundle, arms, colors, args.pair_y)
    written += f1 + f2 + f4 + fp
    written.append(write_readme(args.out, bundle, arms, colors, lmax, kmax, stats,
                                packing, pair_name, args.pair_y))

    print("series: " + ", ".join(
        f"{c} ({' + '.join(h.upper() for h in hexes(colors, c))}"
        + (", two-tone)" if two_tone(colors, c) else ")") for c in arms))
    if dropped:
        print(f"  folded out (structure identical to another arm): {', '.join(dropped)}")
    for c in arms:
        st = stats[c]
        err = 100 * (st["measured"] - st["predicted"]) / st["predicted"]
        print(f"  {c:20s} predicted={st['predicted']:.5f} measured={st['measured']:.5f}"
              f" ({err:+.2f}%)  layers={st['layers']}")
    print(f"fig1a L=1..{lmax}   fig2a k=2..{kmax}")
    for p in written:
        print(f"wrote {p}")
    for p in sorted(args.out.glob("*.dat")):
        print(f"wrote {p}")


if __name__ == "__main__":
    main()
