FIG2A = r"""
%% Figure size and the plotted range of k.
\def\FigWidth{@@W@@}
\def\FigHeight{@@H@@}
\def\KMax{@@KMAX@@}
@@DASHDEFS@@

\begin{tikzpicture}
@@COLORS@@

  \begin{axis}[
      width=\FigWidth, height=\FigHeight,
      xlabel={length of the alternating stretch (cells)},
      ylabel={number of stretches},
      ymode=log,
      xmin=1, xmax=\KMax,
      unbounded coords=jump,
      grid=both,
      major grid style={line width=0.3pt, draw=black!12},
      minor grid style={line width=0.2pt, draw=black!6},
      tick align=outside, tick pos=left,
      axis line style={draw=black!35},
      legend cell align={left},
      legend style={draw=black!20, fill=white, fill opacity=0.9,
                    text opacity=1, font=\small, at={(0.98,0.98)},
                    anchor=north east},
    ]
@@PLOTS@@
  \end{axis}
\end{tikzpicture}
"""


def build_fig2a(out: Path, bundle, arms, colors) -> tuple[list[Path], int]:
    data = bundle["data"]
    hists = {c: data[c]["structure"]["alt_hist"] for c in arms}
    kmax = max(max((k for k, n in h.items() if n >= 5), default=2) for h in hists.values())
    # Same fair-coin law as fig1a, shifted by 1/4 -- the chance the streak is
    # bounded on both sides by a non-singleton block. Emitted so the reference
    # can be switched on, but left out of the plot: fig2a is a count panel.
    n_blocks = sum(data[arms[0]]["structure"]["run_hist"].values())

    header = ["k"] + [color_macro(c) for c in arms] + ["faircoin"]
    rows = []
    for k in range(2, kmax + 1):
        row = [k]
        for c in arms:
            n = hists[c].get(k, 0)
            row.append(n if n else None)
        row.append(n_blocks * 0.5 ** (k + 2))
        rows.append(row)
    write_dat(out / "fig2a_alternating_stretches.dat", header, rows)

    plots = []
    for i, c in enumerate(arms):
        plots.append(f"    %% ---- {c} ----")
        plots += line_series(c, i, colors, "k", color_macro(c),
                             "fig2a_alternating_stretches.dat")
    plots.append("    %% The fair-coin reference is in the .dat as column `faircoin`")
    plots.append("    %% (same geometric law as fig1a, shifted by 1/4). Uncomment to show:")
    plots.append("    %% \\addplot[ndRef, line width=0.9pt, dashed]"
                 " table[x=k, y=faircoin] {fig2a_alternating_stretches.dat};")
    plots.append("    %% \\addlegendentry{random signs}")

    body = (FIG2A.replace("@@COLORS@@", "  " + color_defs(arms, colors).replace("\n", "\n  "))
            .replace("@@PLOTS@@", "\n".join(plots))
            .replace("@@DASHDEFS@@", dash_defs(arms, colors))
            .replace("@@KMAX@@", str(kmax + 1))
            .replace("@@W@@", "8.6cm").replace("@@H@@", "6.2cm"))
    return write_figure(out, "fig2a_alternating_stretches", body), kmax


