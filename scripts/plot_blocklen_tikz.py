#!/usr/bin/env python3
"""Emit pgfplots/TikZ sources for the block-length mechanism panels.

Three figures, the TikZ counterparts of the matplotlib panels in
``scripts/plot_blocklen_png.py``:

  fig1a  block-length distribution -- share of blocks at each length L,
         against the fair-coin reference 2^-L
  fig2a  alternating stretches -- how many maximal streaks of k consecutive
         length-1 blocks the network holds
  fig4a  the identity -- per-layer sign-transition density (predicted) against
         the measured bit errors per misread cell, with the y=x line

Each figure writes

  * ``<name>.dat``            -- the numbers, one column per series
  * ``<name>_body.tex``       -- the figure body, to ``\\input`` into the paper
  * ``<name>.tex``            -- a standalone wrapper to compile on its own

plus a ``README.md`` recording what backs each series. Colours are one
``\\definecolor`` per series at the top of each body file, so re-colouring a
series is a single edit and never needs a regeneration.

Usage::

    python scripts/plot_blocklen_tikz.py
    python scripts/plot_blocklen_tikz.py --only cat1_baseline cat5_regularizer
    python scripts/plot_blocklen_tikz.py --color cat1_baseline=008300 \\
        --color cat5_regularizer=EB6834/EDA100   # two-tone alternating line

Stdlib only -- no matplotlib, no torch, runs on the Mac mount.
"""
