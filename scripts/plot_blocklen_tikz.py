#: The two y-axes fig1a can carry. ``share`` normalises by each arm's OWN block
#: count, so it compares distribution SHAPE. ``count`` has a denominator the arms
#: genuinely share -- both store the same number of cells -- so sum(L * count) is
#: equal across arms and the plot conserves mass: it shows cells moving out of
#: short blocks and into long ones, which normalising away by block count hides.
FIG1A_VIEWS = {
    "share": ("fig1a_blocklen_distribution", "share of all blocks"),
    "count": ("fig1a_blocklen_counts", "number of blocks"),
}


def build_fig1a(out: Path, bundle, arms, colors, views) -> tuple[list[Path], int, dict]:
    data = bundle["data"]
    hists = {c: data[c]["structure"]["run_hist"] for c in arms}
    totals = {c: sum(h.values()) for c, h in hists.items()}
    cells = {c: sum(L * n for L, n in hists[c].items()) for c in arms}
    lmax = max(max((L for L, n in h.items() if n >= 5), default=1) for h in hists.values())
    # The count view's reference needs a block total to scale 2^-L by, and the
    # arms do not share one. The baseline's is the meaningful choice: it IS the
    # random-sign arm, so the dashed line is "what the baseline would hold".
    ref_total = totals[arms[0]]

    n_arms = len(arms)
    written = []
    for view in views:
        # Each view writes its OWN <name>.dat holding only the columns it plots.
        # A shared table would be smaller, but then `fig1a_blocklen_counts.tex`
        # would read a file named after the other figure -- and copying one
        # figure's files into a paper would silently leave its table behind.
        name, ylabel = FIG1A_VIEWS[view]
        dat = f"{name}.dat"
        header = ["L"] + [color_macro(c) for c in arms] + ["faircoin"]
        rows = []
        for L in range(1, lmax + 1):
            counts = [hists[c].get(L, 0) for c in arms]
            row = [L]
            if view == "share":
                row += [(n / totals[c] if n else None) for c, n in zip(arms, counts)]
                row.append(0.5 ** L)
            else:
                row += [(n if n else None) for n in counts]
                row.append(ref_total * 0.5 ** L)
            rows.append(row)
        write_dat(out / dat, header, rows)

        # Floor from the plotted series only: the fair-coin reference runs below
        # the data and would drag the axis down a spare decade. pgfplots clips it.
        vals = [v for row in rows for v in row[1:1 + n_arms] if v is not None]
        ymin = min(vals) / 3

        plots = []
        for i, c in enumerate(arms):
            plots.append(f"    %% ---- {c}"
                         f" ({cells[c]:,} cells in {totals[c]:,} blocks) ----".replace(",", "\\,"))
            plots += line_series(c, i, colors, "L", color_macro(c), dat)
        plots.append("    %% ---- fair coin: a random sign sequence gives 2^-L"
                     + (" ----" if view == "share"
                        else f", here scaled by the baseline's {totals[arms[0]]:,} blocks ----".replace(",", "\\,")))
        plots += ref_series(dat, "L", "faircoin")

        body = (FIG1A.replace("@@COLORS@@", "  " + color_defs(arms, colors).replace("\n", "\n  "))
                .replace("@@PLOTS@@", "\n".join(plots))
                .replace("@@YLABEL@@", ylabel)
                .replace("@@DASHDEFS@@", dash_defs(arms, colors))
                .replace("@@LMAX@@", str(lmax + 1))
                .replace("@@YMIN@@", f"{ymin:.3g}")
                .replace("@@W@@", "8.6cm").replace("@@H@@", "6.2cm"))
        written += write_figure(out, name, body)
    return written, lmax, {"totals": totals, "cells": cells}


